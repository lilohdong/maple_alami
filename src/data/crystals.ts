const PRICES = new Map(TABLE.map(([name, diff, price]) => [`${name}|${diff}`, price * 만]));

/** 인게임/API 표기 → 표의 정식 명칭. 공백 제거 후 비교 */
const ALIASES: [string, string][] = [
  ['감시자칼로스', '칼로스'],
  ['최초의대적자', '대적자'],
  ['선택받은세렌', '세렌'],
  ['찬란한흉성', '흉성'],
  ['가엔슬', '가디언엔젤슬라임'],
  ['카오스', ''], // '카오스 자쿰' 처럼 이름에 난이도가 붙은 경우
];

export function normalizeBossName(name: string): string {
  let n = name.replace(/\s+/g, '');
  for (const [from, to] of ALIASES) n = n.replace(from, to);
  return n;
}

export function normalizeDifficulty(diff: string): string {
  return diff.replace(/\s+/g, '').replace('노말', '노멀');
}

/** 결정석 1개 가격. 표에 없으면 null */
export function crystalPrice(name: string, difficulty: string): number | null {
  return PRICES.get(`${normalizeBossName(name)}|${normalizeDifficulty(difficulty)}`) ?? null;
}

/** 캐릭터별 보스 파티 인원 저장 키 */
export function bossKey(name: string, difficulty: string): string {
  return `${normalizeBossName(name)}|${normalizeDifficulty(difficulty)}`;
}

/** 12.3억 / 4,640만 형태로 축약 */
export function formatMeso(v: number): string {
  if (v >= 1e8) {
    const eok = v / 1e8;
    return `${eok >= 100 ? Math.round(eok) : Number(eok.toFixed(2))}억`;
  }
  if (v >= 1e4) return `${Math.round(v / 1e4).toLocaleString('ko-KR')}만`;
  return v.toLocaleString('ko-KR');
}
